static unsigned char *load(const char *dir,const char *name,size_t *size)
{
    char path[4096];snprintf(path,sizeof path,"%s/%s",dir,name);
    FILE *f=fopen(path,"rb");assert(f);assert(!fseek(f,0,SEEK_END));
    long length=ftell(f);assert(length>0);*size=(size_t)length;rewind(f);
    unsigned char *data=malloc(*size);assert(data && fread(data,1,*size,f)==*size);
    fclose(f);return data;
}
int main(int argc,char **argv)
{
    assert(argc>=2);
    for(int i=1;i<argc;i++){
        size_t ns,rs,ts,qs;unsigned char request[128];time_t when=0;
        unsigned char *nonce=load(argv[i],"nonce.bin",&ns),
            *root=load(argv[i],"test-root.pem",&rs),
            *token=load(argv[i],"issuer-present.der",&ts),
            *expected=load(argv[i],"request.der",&qs);
        assert(ns==32);size_t size=wendy_pki_time_request(request,nonce);
        /* Independently generated by Go encoding/asn1 from the same value. */
        assert(size==qs && !memcmp(request,expected,size));
        assert(!wendy_pki_verify_time(token,ts,nonce,root,rs,0,&when));
        assert(when==1791792000);
        printf("PASS canonical request and signed response: %s (%zu bytes)\n",argv[i],size);
        free(nonce);free(root);free(token);free(expected);
    }
    return 0;
}
